def parse_chats(chats_env):
    chats = []

    for chat in chats_env.split():
        parts = chat.split('_')

        if len(parts) == 2:
            chat_id, topic_id = parts
            chats.append((int(chat_id), int(topic_id)))
        elif len(parts) == 1:
            chats.append((int(parts[0]), None))
        else:
            print(parts[0].isdigit(), parts[0])
            raise ValueError(f"Неверный формат данных CHATS: '{chat}'")

    return chats


